"""Regenerate the offline paper snapshot from the arXiv q-fin.CP feed.

Usage: python3 scripts/generate_snapshot.py
"""

from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from backend.app.arxiv import SOURCE_URL, fetch_papers  # noqa: E402


def main() -> None:
    papers = fetch_papers(count=60, force=True)
    output = ROOT / "public" / "js" / "data" / "snapshot.js"
    output.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "source": SOURCE_URL,
        "papers": papers,
    }
    output.write_text(
        "// Generated by scripts/generate_snapshot.py — do not edit by hand.\n"
        "export const PAPER_SNAPSHOT = "
        + json.dumps(payload, indent=2, ensure_ascii=False)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(papers)} papers to {output}")


if __name__ == "__main__":
    main()
